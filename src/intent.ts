const YEAR = /^(19|20)\d{2}$/;
const VERSION = /^v?\d+(\.\d+)+$/;
// "Best X 2026 review" carries a year but is buyer research, not current
// events. Classifying it as news lets the news engine's 2.0 weight bury the
// review sites (Wirecutter, Food & Wine) under press coverage.
const PRODUCT_HEAD = /\b(?:best|top)\b/i;
const PRODUCT_REVIEW =
  /\b(?:review|reviews|reviewed|tested|testing|buy|buying|comparison)\b/i;

export function isProductQuery(query: string): boolean {
  return PRODUCT_HEAD.test(query) && PRODUCT_REVIEW.test(query);
}

function rawTokens(query: string): string[] {
  return query
    .toLowerCase()
    .split(/[^a-z0-9+#.]+/)
    .filter((token) => token.length > 0);
}

export function classifyIntent(query: string): Intent {
  const tokens = rawTokens(query);
  const devShape =
    /[a-z][A-Z]/.test(query) ||
    tokens.some((token) => token.includes(".") && token.length > 2) ||
    tokens.some((token) => VERSION.test(token)) ||
    query.includes("(") ||
    query.includes(")");
  if (devShape || tokens.some((token) => DEV_WORDS.has(token))) return "dev";
  if (tokens.some((token) => ACADEMIC_WORDS.has(token))) return "academic";
  if (isProductQuery(query)) return "general";
  if (
    tokens.some((token) => YEAR.test(token)) ||
    tokens.some((token) => NEWS_WORDS.has(token))
  )
    return "news";
  return "general";
}

